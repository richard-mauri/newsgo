const newsgoProfileEndpoint = "https://home.themauris.org/api/session/profile"
const newsgoOrigin = "https://newsgo.themauris.org"
var newsgoBearerPattern = regexp.MustCompile(`^Bearer [a-f0-9]{64}$`)

var errNewsgoNoBearer=errors.New("verified Homepage bearer missing")

// NewsGoAuthGate validates every app API request with Homepage. It does not
// authorize based on client role labels, telemetry or a previous page load.
// The initial GET / shell and static assets must be public so a new browser
// can receive its child bearer in a fragment; their content is not authorization.
type NewsGoAuthGate struct {
 ProfileURL string
 Client *http.Client
}

func NewNewsGoAuthGate() *NewsGoAuthGate {
 return &NewsGoAuthGate{
  ProfileURL:newsgoProfileEndpoint,
  Client:&http.Client{Timeout:4*time.Second,CheckRedirect:func(*http.Request,[]*http.Request)error{return http.ErrUseLastResponse}},
 }
}

func (g *NewsGoAuthGate) verify(ctx context.Context,r *http.Request)(suiteauth.Identity,error) {
 authorization:=r.Header.Get("Authorization")
 if !newsgoBearerPattern.MatchString(authorization) {return suiteauth.Identity{},errNewsgoNoBearer}
 if g==nil || g.ProfileURL=="" || g.Client==nil{return suiteauth.Identity{},suiteauth.ErrVerificationUnavailable}
 req,err:=http.NewRequestWithContext(ctx,http.MethodGet,g.ProfileURL,nil)
 if err!=nil{return suiteauth.Identity{},err}
 req.Header.Set("Authorization",authorization)
 req.Header.Set("Origin",newsgoOrigin)
 req.Header.Set("Accept","application/json")
 response,err:=g.Client.Do(req)
 if err!=nil{return suiteauth.Identity{},err}
 defer response.Body.Close()
 if response.StatusCode==http.StatusUnauthorized || response.StatusCode==http.StatusForbidden{return suiteauth.Identity{},nil}
 if response.StatusCode!=http.StatusOK{return suiteauth.Identity{},suiteauth.ErrVerificationUnavailable}
 var profile struct{
  User string `json:"user"`
  Role suiteauth.Role `json:"role"`
  ExpiresAt string `json:"expiresAt"`
 }
 decoder:=json.NewDecoder(io.LimitReader(response.Body,8192))
 if err:=decoder.Decode(&profile);err!=nil{return suiteauth.Identity{},err}
 expiration,err:=time.Parse(time.RFC3339,profile.ExpiresAt)
 if err!=nil || !time.Now().Before(expiration){return suiteauth.Identity{},nil}
 identity:=suiteauth.Identity{User:strings.TrimSpace(profile.User),Role:profile.Role,Verified:true}
 if !suiteauth.Allowed(identity,suiteauth.UseApplication){return suiteauth.Identity{},nil}
 return identity,nil
}

// Protect applies the shared Homepage authorization guard at the outer HTTP
// boundary. Every /api/ route requires a fresh verified personal or Guest
// bearer. Unknown /api paths are guarded too, preventing accidental bypasses.
// Thumbnail request IDs are generated exclusively by NewsGo, never taken from
// a caller header. Logging deliberately omits URL/query, bearer and identity.
var thumbnailRequestSerial atomic.Uint64
var thumbnailCompletedSuccesses atomic.Uint64

type thumbnailTraceIDKey struct{}

type thumbnailResponseCapture struct {
 http.ResponseWriter
 status int
}
func (w *thumbnailResponseCapture) WriteHeader(code int) {
 if w.status!=0{return}
 w.status=code
 w.ResponseWriter.WriteHeader(code)
}
func (w *thumbnailResponseCapture) Write(data []byte)(int,error) {
 if w.status==0{w.status=http.StatusOK}
 return w.ResponseWriter.Write(data)
}
func (w *thumbnailResponseCapture) Unwrap() http.ResponseWriter {return w.ResponseWriter}

func thumbnailRequestID(r *http.Request) string {
 id,_:=r.Context().Value(thumbnailTraceIDKey{}).(string)
 return id
}

// This wrapper sits OUTSIDE the shared Homepage Guard. The guard continues to
// own all authorization decisions. Only /api/thumbnail requests are traced.
func traceThumbnailBoundary(next http.Handler) http.Handler {
 return http.HandlerFunc(func(w http.ResponseWriter,r *http.Request){
  if r.URL.Path!="/api/thumbnail"{next.ServeHTTP(w,r);return}
  id:=strconv.FormatUint(thumbnailRequestSerial.Add(1),10)
  w.Header().Set("X-NewsGo-Request-ID",id)
  captured:=&thumbnailResponseCapture{ResponseWriter:w}
  start:=time.Now()
  next.ServeHTTP(captured,r.WithContext(context.WithValue(r.Context(),thumbnailTraceIDKey{},id)))
  status:=captured.status
  if status==0 && r.Context().Err()!=nil {status=0}
  if status==0 && r.Context().Err()==nil {status=http.StatusOK}
  marked:=captured.Header().Get("X-NewsGo-Thumbnail-Proxy")=="v1"
  if status!=http.StatusOK || !marked {
   outcome:=captured.Header().Get("X-Thumbnail-Outcome")
   // Outcome is generated by NewsGo's handler, not supplied by the browser.
   if outcome=="" {
    if r.Context().Err()!=nil {outcome="client_cancelled"} else if !marked {outcome="before_handler"} else {outcome="handler_error"}
   }
   log.Printf("THUMBNAIL boundary id=%s status=%d handler_marked=%t outcome=%s duration_ms=%d queue_ms=%s upstream_ms=%s",
    id,status,marked,outcome,time.Since(start).Milliseconds(),
    numericThumbnailMetric(captured.Header().Get("X-Thumbnail-Queue-Ms")),
    numericThumbnailMetric(captured.Header().Get("X-Thumbnail-Upstream-Ms")))
  } else if n:=thumbnailCompletedSuccesses.Add(1);n%100==0 {
   log.Printf("THUMBNAIL boundary_success_total=%d (cumulative since NewsGo start)",n)
  }
 })
}
func numericThumbnailMetric(raw string)string {
 if raw==""{return "-"}
 n,e:=strconv.ParseUint(raw,10,64)
 if e!=nil{return "-"}
 return strconv.FormatUint(n,10)
}

func (g *NewsGoAuthGate) Protect(next http.Handler) http.Handler {
 guarded:=suiteauth.Guard(func(ctx context.Context,r *http.Request)(suiteauth.Identity,error){
  identity,err:=g.verify(ctx,r)
  if errors.Is(err,errNewsgoNoBearer){return suiteauth.Identity{},nil}
  return identity,err
 },suiteauth.UseApplication,next)
 return traceThumbnailBoundary(http.HandlerFunc(func(w http.ResponseWriter,r *http.Request){
  if r.URL.Path=="/api"||strings.HasPrefix(r.URL.Path,"/api/"){
   guarded.ServeHTTP(w,r)
   return
  }
  next.ServeHTTP(w,r)
 }))
}
